import { layout } from "./layout";

export function rulesPage(): string {
  const body = `
    <section class="card">
      <h1>게임 규칙</h1>
      <p>주사위 세 개를 굴립니다. 각 주사위는 역할이 고정되어 있습니다.</p>
      <ul>
        <li><strong>퍼스트 다이스 (알파)</strong> — 첫 번째 플레이어의 주사위</li>
        <li><strong>베이스 다이스 (B)</strong> — 기준이 되는 주사위</li>
        <li><strong>라스트 다이스 (베타)</strong> — 두 번째 플레이어의 주사위</li>
      </ul>

      <h2>기본 규칙</h2>
      <p>B(베이스)에 더 가까운 값을 굴린 쪽이 승리합니다.</p>
      <p class="example">예: 알파 1, 베타 6, 베이스 4 → |1-4|=3, |6-4|=2 → 라스트(베타, 6)가 승리</p>

      <h2>예외 1 — 세 주사위의 간격이 같을 때</h2>
      <p>B가 알파·베타 정확히 중간(등거리)에 있으면 기본 규칙만으로는 승자를 정할 수 없습니다. 이때는 두 경우로 나눕니다.</p>
      <ol>
        <li>
          <strong>알파·베타가 각각 1-3 구간과 4-6 구간에 떨어진 경우</strong> — B가 1-3이면 1-3 구간 주사위가,
          B가 4-6이면 4-6 구간 주사위가 승리합니다.
          <div class="example">예: 1-3(B)-5 → B(3)는 1-3 구간 → 1을 굴린 쪽 승리</div>
        </li>
        <li>
          <strong>1-2-3 또는 4-5-6처럼 붙어있는 경우</strong> — 무조건 양 끝 값(1 또는 6)을 굴린 쪽이 승리합니다.
          <div class="example">예: 1-2(B)-3 → 1을 굴린 쪽 승리 · 4-5(B)-6 → 6을 굴린 쪽 승리</div>
        </li>
      </ol>

      <h2>예외 2 — 알파와 베타가 같은 값일 때</h2>
      <p>
        알파와 베타가 같은 숫자가 나오면, 알파는 1-3 구간, 베타는 4-6 구간을 대표하는 것으로 간주합니다.
        B가 1-3이면 퍼스트(알파)가, B가 4-6이면 라스트(베타)가 승리합니다.
      </p>

      <h2>무승부가 없는 이유</h2>
      <p>
        위 규칙을 6&times;6&times;6 = 216가지 조합 전체에 적용하면 예외 없이 정확히 한 명의 승자가 정해집니다.
        (알파=베타는 항상 예외 2로, 등거리이면서 알파&ne;베타인 경우는 항상 예외 1로 흡수되어
        기본 규칙이 애매해지는 경우가 남지 않습니다.)
      </p>
    </section>
  `;
  return layout({ title: "규칙 설명", body, activeNav: "rules" });
}
